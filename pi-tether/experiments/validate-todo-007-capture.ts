import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { MOM_PROMPT } from "../src/contract.ts";
import { checkGraph } from "../src/graph.ts";
import { presentGraph, readText } from "../src/presentation.ts";

const path = new URL("./evidence/todo-007-real-luna-purpose-map.json", import.meta.url);
const raw = await readFile(path, "utf8"), artifact = JSON.parse(raw);
assert.equal(artifact.schema, "todo-007-real-luna-capture");
assert.deepEqual(artifact.model, { provider: "openai-codex", id: "gpt-5.6-luna", reasoning: "low" });
assert.match(artifact.isolation, /no user session JSONL or \.mom file was opened or written/);
assert.equal(artifact.promptSha256, createHash("sha256").update(MOM_PROMPT).digest("hex"));
assert(Array.isArray(artifact.calls) && artifact.calls.length >= 1 && artifact.calls.length <= 2, "capture must stay inside the background two-call ceiling");
assert(artifact.calls.every((call: any) => call.operations?.length === 1 && call.operations[0].name === "commit_graph"));
assert(Object.values(artifact.checks).every(Boolean), "all predeclared purpose-map checks must pass");
checkGraph(artifact.graph);
assert.equal(artifact.graph.motherThread, artifact.graph.purpose);
assert.equal(artifact.graph.nodes.filter((node: any) => node.parent === null).length, 1);
const refs = new Set(artifact.fixture.map((event: any) => event.ref));
for (const item of [...artifact.graph.nodes, ...artifact.graph.edges]) for (const source of item.sources) assert(refs.has(source), `unreopenable capture source: ${source}`);
assert.equal(artifact.graphSha256, createHash("sha256").update(JSON.stringify(artifact.graph)).digest("hex"));
const story = readText(presentGraph({ ...artifact.graph, roots: [artifact.graph.motherThread], focusPath: [], boundaryNodes: [], totalNodes: artifact.graph.nodes.length, omittedNodes: 0 }));
assert.equal(artifact.story, story);
assert.match(story, /^Mother thread:/);
assert.match(story, /Why: \[src:capture:user:origin\]/);
assert.match(story, /Depends on: Obtain a cold-reload proof/);
assert.match(story, /Alternative to: Accept the production Mom map/);
assert.match(story, /Replay the transcript .* waiting/);
assert.doesNotMatch(raw, /(?:sk-[A-Za-z0-9]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|Authorization\s*[:=]|Bearer\s+[A-Za-z0-9._-]{16,})/i);
console.log(JSON.stringify({ valid: true, calls: artifact.calls.length, nodes: artifact.graph.nodes.length, graphSha256: artifact.graphSha256 }));
